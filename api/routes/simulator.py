"""Authenticated endpoints for safe, synthetic attack-simulation evaluation.

These endpoints run the local rule engine on synthetic events only. They do not
execute AWS API calls or remediation actions.
"""
from pathlib import Path
import re
from fastapi import APIRouter, Depends, HTTPException, Query

from core.auth import CurrentUser, get_current_user, require_min_role
from simulation.runner import latest_report, run_simulation
from simulation.scenarios import list_scenarios

router = APIRouter(prefix="/simulator", tags=["Attack Simulator"])
_BASE_DIR = Path("./data/simulations")


def _user_dir(user: CurrentUser) -> Path:
    # Organization ID is generated by the app; normalize anyway before path use.
    org_id = re.sub(r"[^a-zA-Z0-9_-]", "", user.organization_id or "")
    if not org_id:
        raise HTTPException(status_code=400, detail="User organization is not configured.")
    return _BASE_DIR / org_id


@router.get("/scenarios")
async def scenarios(current_user: CurrentUser = Depends(get_current_user)):
    """List built-in synthetic scenarios. No AWS resources are changed."""
    return {"mode": "synthetic_offline", "scenarios": list_scenarios()}


@router.post("/run")
async def run_once(
    threshold: int = Query(default=30, ge=0, le=100),
    current_user: CurrentUser = Depends(require_min_role("analyst")),
):
    """Run one batch of offline scenarios through the current detection rules."""
    report = run_simulation(results_dir=_user_dir(current_user), severity_threshold=threshold)
    # Avoid exposing local filesystem paths through the API.
    report.pop("report_path", None)
    return report


@router.get("/latest")
async def get_latest(current_user: CurrentUser = Depends(get_current_user)):
    """Return the latest evaluation report for the caller's organization."""
    report = latest_report(results_dir=_user_dir(current_user))
    if report is None:
        return {"report": None, "message": "No evaluation runs yet. Start one with POST /simulator/run."}
    report.pop("report_path", None)
    return {"report": report}


@router.get("/history")
async def history(
    limit: int = Query(default=10, ge=1, le=100),
    current_user: CurrentUser = Depends(get_current_user),
):
    """List recent evaluation summaries for the caller's organization."""
    directory = _user_dir(current_user)
    if not directory.exists():
        return {"runs": []}
    files = sorted(directory.glob("sim-*.json"), key=lambda p: p.stat().st_mtime, reverse=True)[:limit]
    runs = []
    import json
    for file in files:
        try:
            report = json.loads(file.read_text(encoding="utf-8"))
            runs.append({
                "run_id": report.get("run_id"),
                "generated_at": report.get("generated_at"),
                "scenario_count": report.get("scenario_count"),
                "confusion_matrix": report.get("confusion_matrix"),
                "metrics": report.get("metrics"),
                "mode": report.get("mode", "synthetic_offline"),
            })
        except (OSError, json.JSONDecodeError):
            continue
    return {"runs": runs}
